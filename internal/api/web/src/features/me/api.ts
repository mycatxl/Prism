import { apiRequest } from "../../lib/api-client";
import type {
  AccessKeyInput,
  BalanceView,
  CreateKeyResponse,
  DepositInfo,
  DepositIntent,
  DepositIntentsResponse,
  KeysResponse,
  PurchaseResult,
  PurchasablePlan,
  SelfLease,
  SelfOverview,
  SessionsResponse,
  SubscriptionView,
} from "./types";

export async function getOverview(): Promise<SelfOverview> {
  return apiRequest<SelfOverview>("/api/v1/me/overview");
}

export async function getBalance(limit?: number): Promise<BalanceView> {
  const query = limit && limit > 0 ? `?limit=${limit}` : "";
  return apiRequest<BalanceView>(`/api/v1/me/balance${query}`);
}

export async function redeemCode(code: string): Promise<BalanceView> {
  return apiRequest<BalanceView>("/api/v1/me/redeem", {
    method: "POST",
    body: { code },
  });
}

export async function getPlans(): Promise<{ items: PurchasablePlan[] }> {
  return apiRequest<{ items: PurchasablePlan[] }>("/api/v1/me/plans");
}

/**
 * Buys a plan with the caller's balance.
 *
 * `request_id` is generated by the caller and is what makes a retry safe: the
 * second request carrying the same id is answered with the first one's result
 * rather than charged again.
 */
export async function purchase(planID: string, requestID: string): Promise<PurchaseResult> {
  return apiRequest<PurchaseResult>("/api/v1/me/purchases", {
    method: "POST",
    body: { plan_id: planID, request_id: requestID },
  });
}

/**
 * Extends the caller's own subscription by one period.
 *
 * `request_id` is minted by the dialog and kept for its lifetime, so pressing
 * renew twice - or retrying after a dropped response - charges one period.
 */
export async function renew(subscriptionID: string, requestID: string): Promise<PurchaseResult> {
  return apiRequest<PurchaseResult>("/api/v1/me/renewals", {
    method: "POST",
    body: { subscription_id: subscriptionID, request_id: requestID },
  });
}

export async function setAutoRenew(
  subscriptionID: string,
  autoRenew: boolean,
): Promise<{ subscription: SubscriptionView }> {
  return apiRequest<{ subscription: SubscriptionView }>("/api/v1/me/subscription", {
    method: "PATCH",
    body: { subscription_id: subscriptionID, auto_renew: autoRenew },
  });
}

export async function getLeases(): Promise<{ items: SelfLease[] }> {
  return apiRequest<{ items: SelfLease[] }>("/api/v1/me/leases");
}

export async function releaseLease(platformID: string, account: string): Promise<void> {
  return apiRequest<void>(
    `/api/v1/me/leases/${encodeURIComponent(platformID)}/${encodeURIComponent(account)}`,
    { method: "DELETE" },
  );
}

export async function getKeys(): Promise<KeysResponse> {
  return apiRequest<KeysResponse>("/api/v1/me/keys");
}

export async function createKey(input: AccessKeyInput): Promise<CreateKeyResponse> {
  return apiRequest<CreateKeyResponse>("/api/v1/me/keys", {
    method: "POST",
    body: input,
  });
}

export async function deleteKey(keyID: string): Promise<void> {
  return apiRequest<void>(`/api/v1/me/keys/${encodeURIComponent(keyID)}`, {
    method: "DELETE",
  });
}

export async function getSessions(): Promise<SessionsResponse> {
  return apiRequest<SessionsResponse>("/api/v1/me/security/sessions");
}

export async function revokeSession(sessionID: string): Promise<void> {
  return apiRequest<void>(`/api/v1/me/security/sessions/${encodeURIComponent(sessionID)}`, {
    method: "DELETE",
  });
}

export async function getDepositInfo(): Promise<DepositInfo> {
  return apiRequest<DepositInfo>("/api/v1/me/deposit");
}

export async function openDeposit(amountMicro: number): Promise<DepositIntent> {
  return apiRequest<DepositIntent>("/api/v1/me/deposits", {
    method: "POST",
    body: { amount_micro: amountMicro },
  });
}

export async function getDepositIntents(): Promise<DepositIntentsResponse> {
  return apiRequest<DepositIntentsResponse>("/api/v1/me/deposits");
}
