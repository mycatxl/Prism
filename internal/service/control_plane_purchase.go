// Buying and renewing a subscription with a balance.
//
// Two rules run through this file.
//
// The price is the one the customer agreed to. A subscription carries the
// snapshot of the plan it was sold under, so a plan edited afterwards does not
// silently reprice what somebody already bought. The fallback is the one gap
// that rule leaves: a subscription created before prices existed carries a
// snapshot with no price in it, and reading that as "free" would let those
// customers renew forever without paying. So a snapshot price of zero or less
// means "never priced", the live plan's price applies, and it is written back
// into the snapshot - once. An operator who wants to reprice an existing
// subscription on purpose uses apply_to_existing, which rewrites the snapshot
// of everybody on the plan.
//
// A charge and what it bought commit together. The transaction lives in the
// repository (PurchasePlanWithBalance, RenewSubscriptionWithBalance), because a
// service-level "charge, then subscribe" has a window in which the customer has
// paid and has nothing.

const (
	// renewalLeadTime is how far ahead the sweep looks. It matches the 7-day
	// window the console already warns in (expiringSoonDays), so a customer is
	// never renewed before the panel has told them it is about to happen.
	renewalLeadTimeNs = int64(7) * 24 * 60 * 60 * 1_000_000_000
	// maxPurchaseRequestID bounds a client-supplied idempotency key. It lands
	// in an index, so it is bounded like every other caller-supplied identifier.
	maxPurchaseRequestID = 128
)

// PurchasablePlan is a plan a customer can buy without an operator.
type PurchasablePlan struct {
	ID           string   `json:"id"`
	Name         string   `json:"name"`
	Platforms    []string `json:"platforms"`
	IPTiers      []string `json:"ip_tiers"`
	TrafficBytes int64    `json:"traffic_bytes"`
	Period       string   `json:"period"`
	DurationDays int      `json:"duration_days"`
	PriceMicro   int64    `json:"price_micro"`
}

// PurchaseInput is the accepted body of a self-service purchase.
//
// RequestID is generated by the client and is what makes a retry safe: the
// second request carrying the same id is answered with the first one's result
// rather than charged again.
type PurchaseInput struct {
	PlanID    string `json:"plan_id"`
	RequestID string `json:"request_id"`
}

// PurchaseResultView is what a purchase answers with.
type PurchaseResultView struct {
	Subscription SubscriptionView `json:"subscription"`
	BalanceMicro int64            `json:"balance_micro"`
	// ChargedMicro is what this call took. Zero on a replay, which is what
	// makes "did I just get charged twice" answerable from the response.
	ChargedMicro int64 `json:"charged_micro"`
	Replayed     bool  `json:"replayed"`
}

// RenewalView reports one pass of the renewal sweep.
type RenewalView struct {
	// Renewed is how many subscriptions were extended and charged.
	Renewed int `json:"renewed"`
	// ShortOfFunds is how many could not be renewed because the balance did
	// not cover the price. They are left alone and reported, never silently
	// skipped.
	ShortOfFunds int `json:"short_of_funds"`
	// Failed is how many errored for any other reason.
	Failed int `json:"failed"`
}

// SelfPlans returns the plans a customer may buy.
//
// A plan with no price is not for sale. That is not the same as free: an
// operator grants it, and listing it here would offer a purchase that would
// have to be refused. A disabled plan is not for sale either, which is what
// makes disabling a plan an emergency stop rather than a statement about the
// future.
func (s *ControlPlaneService) SelfPlans() ([]PurchasablePlan, error) {
	if s == nil || s.Engine == nil {
		return nil, internal("no state engine", nil)
	}
	plans, err := s.Engine.ListPlans()
	if err != nil {
		return nil, internal("list plans", err)
	}

	result := make([]PurchasablePlan, 0, len(plans))
	for _, plan := range plans {
		if plan.Status != planStatusActive || plan.PriceMicro <= 0 {
			continue
		}
		result = append(result, PurchasablePlan{
			ID:           plan.ID,
			Name:         plan.Name,
			Platforms:    plan.Platforms,
			IPTiers:      plan.IPTiers,
			TrafficBytes: plan.TrafficBytes,
			Period:       plan.Period,
			DurationDays: plan.DurationDays,
			PriceMicro:   plan.PriceMicro,
		})
	}
	return result, nil
}

// SelfPurchase buys a plan with the caller's balance.
//
// The new subscription replaces whatever the user had running, the same way an
// operator's assign does: a user has at most one active subscription, so
// buying is "last purchase wins" rather than stacking windows.
func (s *ControlPlaneService) SelfPurchase(userID string, in PurchaseInput, nowNs int64) (PurchaseResultView, error) {
	if s == nil || s.Engine == nil {
		return PurchaseResultView{}, internal("no state engine", nil)
	}
	if _, err := s.Engine.GetUser(userID); err != nil {
		return PurchaseResultView{}, mapUserLookupError(err)
	}
	planID := strings.TrimSpace(in.PlanID)
	if planID == "" {
		return PurchaseResultView{}, invalidArg("plan_id: required")
	}
	requestID := strings.TrimSpace(in.RequestID)
	if len(requestID) > maxPurchaseRequestID {
		return PurchaseResultView{}, invalidArg("request_id: too long")
	}

	plan, err := s.Engine.GetPlan(planID)
	if err != nil {
		return PurchaseResultView{}, mapPlanLookupError(err)
	}
	if plan.Status != planStatusActive {
		return PurchaseResultView{}, invalidArg("plan_id: the plan is disabled")
	}
	if plan.PriceMicro <= 0 {
		return PurchaseResultView{}, invalidArg("plan_id: the plan is not for sale")
	}
	if plan.DurationDays <= 0 {
		return PurchaseResultView{}, invalidArg("plan_id: the plan has no duration")
	}

	snapshot, err := planSnapshotJSON(*plan)
	if err != nil {
		return PurchaseResultView{}, internal("encode plan snapshot", err)
	}
	subID, err := newID("us_")
	if err != nil {
		return PurchaseResultView{}, internal("generate subscription id", err)
	}
	entryID, err := newID("bl_")
	if err != nil {
		return PurchaseResultView{}, internal("generate ledger id", err)
	}

	row := model.UserSubscription{
		ID:               subID,
		UserID:           userID,
		PlanID:           plan.ID,
		PlanSnapshotJSON: snapshot,
		StartsAtNs:       nowNs,
		ExpiresAtNs:      expiryFromDays(plan.DurationDays, nowNs),
		PeriodStartNs:    nowNs,
		Status:           model.SubscriptionStatusActive,
	}
	result, err := s.Engine.PurchasePlanWithBalance(row, model.BalanceEntry{
		ID:          entryID,
		UserID:      userID,
		DeltaMicro:  -plan.PriceMicro,
		Reason:      model.BalanceReasonPurchase,
		RefID:       plan.ID,
		RequestID:   requestID,
		CreatedAtNs: nowNs,
	}, nowNs)
	if errors.Is(err, state.ErrInsufficientBalance) {
		return PurchaseResultView{}, invalidArg("balance: not enough to buy this plan")
	}
	if errors.Is(err, state.ErrConflict) {
		return PurchaseResultView{}, conflict("that purchase could not be settled; retry with a new request_id")
	}
	if err != nil {
		return PurchaseResultView{}, internal("purchase plan", err)
	}

	// The running aggregate belongs to the subscription that just ended. A new
	// window starts at zero bytes on disk, so the in-memory total has to follow
	// or the quota would refuse a user who has used nothing.
	if s.Usage != nil {
		s.Usage.ResetUser(userID)
	}
	// The new plan is in force from the next request rather than the next
	// restart.
	if err := s.republishUserKeys(userID); err != nil {
		return PurchaseResultView{}, err
	}

	view := PurchaseResultView{
		BalanceMicro: result.Entry.BalanceAfterMicro,
		ChargedMicro: -result.Entry.DeltaMicro,
		Replayed:     result.Replayed,
	}
	if result.Replayed {
		view.ChargedMicro = 0
	}
	views, err := s.subscriptionViews([]model.UserSubscription{result.Subscription})
	if err != nil {
		return PurchaseResultView{}, err
	}
	view.Subscription = views[0]
	return view, nil
}

// SetAutoRenew turns the caller's own renewal switch on or off.
//
// Ownership is checked by reading the row through the user's own id: a
// subscription id learnt elsewhere matches nothing, so there is no separate
// authorisation step to forget.
func (s *ControlPlaneService) SetAutoRenew(userID, subscriptionID string, autoRenew bool) (SubscriptionView, error) {
	if s == nil || s.Engine == nil {
		return SubscriptionView{}, internal("no state engine", nil)
	}
	subscriptionID = strings.TrimSpace(subscriptionID)
	if subscriptionID == "" {
		return SubscriptionView{}, invalidArg("subscription_id: required")
	}
	row, err := s.Engine.GetUserSubscription(subscriptionID)
	if err != nil {
		return SubscriptionView{}, mapSubscriptionLookupError(err)
	}
	if row.UserID != userID {
		return SubscriptionView{}, notFound("subscription not found")
	}
	if err := s.Engine.SetSubscriptionAutoRenew(row.ID, autoRenew); err != nil {
		if errors.Is(err, state.ErrNotFound) {
			return SubscriptionView{}, notFound("subscription not found")
		}
		return SubscriptionView{}, internal("set auto renew", err)
	}
	row.AutoRenew = autoRenew
	views, err := s.subscriptionViews([]model.UserSubscription{*row})
	if err != nil {
		return SubscriptionView{}, err
	}
	return views[0], nil
}

// SelfAutoRenew reads the caller's own subscription, which is where the
// renewal switch and its price live.
func (s *ControlPlaneService) SelfAutoRenew(userID string) (*SubscriptionView, error) {
	return s.SelfSubscription(userID)
}

// RenewDueSubscriptions charges and extends every subscription that opted in
// and is inside the lead time before its expiry.
//
// A subscription whose balance does not cover the price is left exactly as it
// is and counted in ShortOfFunds. It is not extended on credit and it is not
// quietly skipped: the count is what an operator sees, and the panel shows the
// user their own shortfall.
//
// Every write goes through republishUserKeys, because the data plane reads the
// expiry from the in-memory snapshot: an extension that is not republished
// leaves the user refused by a clock that has already been moved on disk.
func (s *ControlPlaneService) RenewDueSubscriptions(nowNs int64) (RenewalView, error) {
	if s == nil || s.Engine == nil {
		return RenewalView{}, internal("no state engine", nil)
	}
	if nowNs <= 0 {
		return RenewalView{}, invalidArg("now_ns: must be positive")
	}
	due, err := s.Engine.ListRenewableSubscriptions(nowNs, renewalLeadTimeNs)
	if err != nil {
		return RenewalView{}, internal("list renewable subscriptions", err)
	}

	var result RenewalView
	for _, sub := range due {
		renewed, err := s.renewOne(sub, nowNs)
		switch {
		case err == nil && renewed:
			result.Renewed++
		case errors.Is(err, state.ErrInsufficientBalance):
			result.ShortOfFunds++
		default:
			result.Failed++
		}
	}
	return result, nil
}

// renewOne renews a single subscription, reporting whether it was charged.
func (s *ControlPlaneService) renewOne(sub model.UserSubscription, nowNs int64) (bool, error) {
	plan, snapshotPrice, err := s.renewalPrice(sub)
	if err != nil {
		return false, err
	}
	if plan.DurationDays <= 0 {
		return false, nil
	}

	entryID, err := newID("bl_")
	if err != nil {
		return false, err
	}
	updated := sub
	updated.ExpiresAtNs = expiryFromDays(plan.DurationDays, maxInt64(sub.ExpiresAtNs, nowNs))
	updated.PeriodIndex = sub.PeriodIndex + 1
	// A snapshot with no price in it is written back with the price it is
	// being charged, so the fallback happens once rather than every period.
	if snapshotPrice <= 0 {
		snapshot, encodeErr := planSnapshotJSON(plan)
		if encodeErr != nil {
			return false, encodeErr
		}
		updated.PlanSnapshotJSON = snapshot
	}

	if _, err := s.Engine.RenewSubscriptionWithBalance(updated, sub.PeriodIndex, model.BalanceEntry{
		ID:          entryID,
		UserID:      sub.UserID,
		DeltaMicro:  -plan.PriceMicro,
		Reason:      model.BalanceReasonRenew,
		RefID:       sub.ID,
		RequestID:   renewalRequestID(sub),
		CreatedAtNs: nowNs,
	}); err != nil {
		return false, err
	}
	if s.Usage != nil {
		s.Usage.ResetUser(sub.UserID)
	}
	if err := s.republishUserKeys(sub.UserID); err != nil {
		return false, err
	}
	return true, nil
}

// renewalPrice resolves what a renewal costs.
//
// The snapshot is the contract, so its price wins. A snapshot that predates
// prices carries zero, which is "never priced" rather than "free", and the live
// plan answers instead. A plan that no longer exists and a snapshot with no
// price is a subscription that cannot be priced at all, and it is left alone:
// charging zero would renew it forever for nothing.
func (s *ControlPlaneService) renewalPrice(sub model.UserSubscription) (model.Plan, int64, error) {
	plan, err := planFromSnapshotJSON(sub.PlanSnapshotJSON)
	if err != nil {
		return model.Plan{}, 0, internal("read plan snapshot", err)
	}
	snapshotPrice := plan.PriceMicro
	if snapshotPrice > 0 {
		return plan, snapshotPrice, nil
	}
	if sub.PlanID == "" {
		return model.Plan{}, 0, invalidArg("plan_id: the subscription has no plan to renew against")
	}
	live, err := s.Engine.GetPlan(sub.PlanID)
	if err != nil {
		return model.Plan{}, 0, mapPlanLookupError(err)
	}
	if live.PriceMicro <= 0 {
		return model.Plan{}, 0, invalidArg("price_micro: the plan is not priced")
	}
	return *live, 0, nil
}

// renewalRequestID is the idempotency key of one period's charge.
//
// It is derived from the subscription and the period rather than generated, so
// a retried sweep collides with the charge it already made instead of adding a
// second one. The period index is bumped in the same transaction, so a charge
// that committed cannot be repeated: the next pass reads a higher index and a
// different key.
func renewalRequestID(sub model.UserSubscription) string {
	return "renew:" + sub.ID + ":" + strconv.Itoa(sub.PeriodIndex)
}

func maxInt64(a, b int64) int64 {
	if a > b {
		return a
	}
	return b
}
